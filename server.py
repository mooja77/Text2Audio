async def _read_upload(upload: UploadFile, limit: int) -> bytes:
    data = bytearray()
    while chunk := await upload.read(min(1024 * 1024, limit + 1 - len(data))):
        data.extend(chunk)
        if len(data) > limit:
            raise HTTPException(status_code=413, detail="upload is too large")
    return bytes(data)

