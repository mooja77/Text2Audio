@app.get("/api/audio/{id}")
def library_audio(id: str):
    _check_id(id)
    path = library.audio_path(id)
    if not os.path.isfile(path):
        raise HTTPException(status_code=404, detail="no audio")
    return FileResponse(path, media_type="audio/mp4")  # Starlette handles Range -> 206


@app.get("/api/cover/{id}")
def library_cover(id: str):
    _check_id(id)
    p = library.cover_path(id)
    if not p:
        raise HTTPException(status_code=404, detail="no cover")
    return FileResponse(p, media_type="image/jpeg")


class RetagRequest(BaseModel):
    title: str | None = None
    author: str | None = None


class RemasterRequest(BaseModel):
    bitrate: str = "128k"
    master: bool = True


class PronRule(BaseModel):
    sayAs: str


class NormalizePreviewRequest(BaseModel):
    text: str


@app.post("/api/library/{id}/retag")
def library_retag(id: str, req: RetagRequest):
    _check_id(id)
    m = library.get(id)
    if m is None:
        raise HTTPException(status_code=404, detail="not found")
    if req.title is not None:
        m["title"] = req.title
    if req.author is not None:
        m["author"] = req.author
    library.save_manifest(id, m)
    return m


@app.delete("/api/library/{id}")
def library_delete(id: str):
    _check_id(id)
    if library.get(id) is None:
        raise HTTPException(status_code=404, detail="not found")
    library.delete(id)
    return {"deleted": id}


class PreviewRequest(BaseModel):
    voice: str


_PREVIEW_TEXT = "This is a sample of the selected narrator voice."


@app.post("/api/voice-preview")
def voice_preview(req: PreviewRequest):
    if req.voice not in PRESET_VOICES and voices.get(req.voice) is None:
        raise HTTPException(status_code=400, detail="unknown voice")
    synth = SYNTH_FACTORY(req.voice, 1.0)
    try:
        if hasattr(synth, "preview"):
            audio = synth.preview(_PREVIEW_TEXT)
        else:
            audio = synth.synth_chunks([_PREVIEW_TEXT])
    finally:
        if hasattr(synth, "close"):
            synth.close()
    buf = io.BytesIO()
    sf.write(buf, audio, SAMPLE_RATE, format="WAV")
    return Response(content=buf.getvalue(), media_type="audio/wav")


@app.post("/api/library/{id}/remaster")
def library_remaster(id: str, req: RemasterRequest = RemasterRequest()):
    _check_id(id)
    try:
        return remaster(library, id, bitrate=req.bitrate, master=req.master)
    except FileNotFoundError:
        raise HTTPException(status_code=404, detail="not found")
    except ValueError as e:
        raise HTTPException(status_code=400, detail=str(e))


@app.post("/api/library/{id}/purge-wav")
def library_purge(id: str):
    _check_id(id)
    try:
        return purge_wavs(library, id)
    except FileNotFoundError:
        raise HTTPException(status_code=404, detail="not found")


@app.get("/api/pronunciations")
def pronunciations_list():
    return {"builtin": BUILTIN_PRONUNCIATIONS, "custom": pron.get_all()}


@app.put("/api/pronunciations/{word}")
def pronunciations_set(word: str, rule: PronRule):
    if not rule.sayAs.strip():
        raise HTTPException(status_code=400, detail="sayAs is required")
    pron.set_rule(word, rule.sayAs.strip())
    return {"custom": pron.get_all()}


@app.delete("/api/pronunciations/{word}")
def pronunciations_remove(word: str):
    pron.remove(word)
    return {"custom": pron.get_all()}


@app.post("/api/normalize-preview")
def normalize_preview(req: NormalizePreviewRequest):
    return {"normalized": normalize_text(req.text, pron.get_all())}


@app.post("/api/voices/clone")
async def voices_clone(name: str = Form(...), audio: UploadFile = File(...),
                       refText: str = Form("")):
    if not name.strip():
        raise HTTPException(status_code=400, detail="name is required")
    data = await audio.read()
    if not data:
        raise HTTPException(status_code=400, detail="audio is required")
    ext = os.path.splitext(audio.filename or "")[1] or ".wav"
    try:
        return voices.create(name.strip(), data, ext, refText.strip())
    except ValueError as e:
        raise HTTPException(status_code=400, detail=str(e))


@app.delete("/api/voices/{id}")
def voices_delete(id: str):
    if voices.get(id) is None:
        raise HTTPException(status_code=404, detail="not found")
    voices.delete(id)
    return {"deleted": id}


