@app.post("/api/library/{id}/retag")
def library_retag(id: str, req: RetagRequest):
    _check_id(id)
    m = library.get(id)
    if m is None:
        raise HTTPException(status_code=404, detail="not found")
    title = req.title if req.title is not None else m.get("title", "")
    author = req.author if req.author is not None else m.get("author", "")
    with _maintenance_lock:
        retag_audio(library, id, title, author)
        m["title"], m["author"] = title, author
        library.save_manifest(id, m)
    return m


