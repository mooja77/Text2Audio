ROOT = Path(__file__).parent
WEB_DIR = ROOT / "web"
LIBRARY_DIR = os.environ.get("T2A_LIBRARY_DIR", str(ROOT / "library"))

library = Library(LIBRARY_DIR)
PRON_PATH = os.environ.get("T2A_PRON_PATH", os.path.join(os.path.dirname(LIBRARY_DIR), "data", "pronunciations.json"))
pron = PronunciationStore(PRON_PATH)
VOICES_DIR = os.environ.get("T2A_VOICES_DIR", os.path.join(os.path.dirname(LIBRARY_DIR), "voices"))
voices = VoiceStore(VOICES_DIR)
jobs = JobManager()
_render_lock = threading.Lock()      # one GPU render at a time

# Library ids are generated by new_id() as 10 lowercase hex chars. Validate any
# id taken from a request before it touches the filesystem (defends rmtree etc.).
_ID_RE = re.compile(r"^[0-9a-f]{6,32}$")


def _check_id(id: str) -> None:
    if not _ID_RE.match(id):
        raise HTTPException(status_code=404, detail="not found")

_ACCENT = {"a": "American", "b": "British"}
_VOICE_LABELS = {"af_heart": "Heart", "af_bella": "Bella", "af_nicole": "Nicole",
                 "af_sarah": "Sarah", "af_sky": "Sky", "am_michael": "Michael",
                 "am_adam": "Adam", "am_echo": "Echo", "am_liam": "Liam",
                 "bf_emma": "Emma", "bf_isabella": "Isabella", "bf_alice": "Alice",
                 "bm_george": "George", "bm_lewis": "Lewis", "bm_daniel": "Daniel"}


class RenderRequest(BaseModel):
    bookText: str
    voice: str = "af_heart"
    speed: float = 1.0
    title: str = ""
    author: str = ""
    # NOTE: no client-supplied filesystem path here. A cover would be uploaded as
    # bytes via multipart and validated before saving — never a server-side path.


def voices_payload() -> list[dict]:
    out = []
    for vid, lang in PRESET_VOICES.items():
        out.append({"id": vid, "label": _VOICE_LABELS.get(vid, vid),
                    "accent": _ACCENT.get(lang, lang),
                    "gender": "Female" if vid[1] == "f" else "Male", "kind": "preset"})
    for v in voices.list():
        out.append({"id": v["id"], "label": v["name"], "name": v["name"],
                    "accent": "Cloned", "gender": "", "kind": "cloned"})
    return out


def resolve_synth(voice_id, speed):
    if voice_id in PRESET_VOICES:
        return Synthesizer(voice=voice_id, lang_code=PRESET_VOICES[voice_id], speed=float(speed))
    meta = voices.get(voice_id)
    if meta is None:
        raise KeyError(voice_id)
    return ClonedSynthesizer(voices.ref_path(voice_id), meta.get("refText", ""), float(speed))


SYNTH_FACTORY = resolve_synth


@asynccontextmanager
async def lifespan(app: FastAPI):
    app.state.ffmpeg_ok = shutil.which("ffmpeg") is not None
    if not app.state.ffmpeg_ok:
        print("WARNING: ffmpeg not found on PATH — audio assembly will fail.", file=sys.stderr)
    yield


app = FastAPI(title="Text2Audio Studio", lifespan=lifespan)


@app.get("/api/health")
def health():
    return {"status": "ok", "ffmpeg": shutil.which("ffmpeg") is not None}


@app.get("/api/voices")
def get_voices():
    return voices_payload()


@app.get("/")
def index():
    return FileResponse(WEB_DIR / "index.html")


@app.post("/api/ingest")
async def ingest(files: list[UploadFile] = File(...)):
    sources = []
    for f in files:
        raw = (await f.read()).decode("utf-8", errors="replace")
        sources.append((f.filename or "untitled.txt", raw))
    book_text = build_book_text(sources)
    chapters = parse_chapters(book_text)
    return {
        "bookText": book_text,
        "chapters": [{"index": i, "title": c.title, "chars": len(c.text)}
                     for i, c in enumerate(chapters)],
    }


@app.post("/api/render")
def start_render(req: RenderRequest):
    if req.voice not in PRESET_VOICES and voices.get(req.voice) is None:
        raise HTTPException(status_code=400, detail="unknown voice")
    # Serialize renders: concurrent GPU inference from two threads is unsafe.
    if not _render_lock.acquire(blocking=False):
        raise HTTPException(status_code=409, detail="A render is already in progress")
    job_id = new_id()

    def target(emit):
        try:
            render_audiobook(book_text=req.bookText, voice=req.voice, speed=req.speed,
                             title=req.title, author=req.author, cover_path=None,
                             library=library, job_id=job_id, emit=emit,
                             synth_factory=SYNTH_FACTORY, custom_rules=pron.get_all())
        finally:
            _render_lock.release()

    jobs.submit(job_id, target)
    return {"jobId": job_id}


@app.get("/api/render/{job_id}/stream")
async def render_stream(job_id: str, request: Request):
    return StreamingResponse(jobs.stream(job_id, request), media_type="text/event-stream",
                             headers={"Cache-Control": "no-cache", "X-Accel-Buffering": "no"})


@app.get("/api/library")
def library_list():
    return library.list()


@app.get("/api/library/{id}")
def library_detail(id: str):
    _check_id(id)
    m = library.get(id)
    if m is None:
        raise HTTPException(status_code=404, detail="not found")
